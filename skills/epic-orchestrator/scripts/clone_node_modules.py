"""Clone a Yarn 1 monorepo's node_modules from a source checkout into a target
worktree using APFS copy-on-write via clonefile(2).

One clonefile() syscall per node_modules directory hands the full subtree to
the kernel in a single atomic operation. Symlinks are cloned as symlinks with
their relative targets preserved, so workspace packages (e.g.
node_modules/@attentive/foo -> ../../libs/foo) resolve within the target
worktree, not back to the source. APFS shares underlying extents until a file
is written to, so per-worktree mutations are isolated without any up-front copy
cost.

Usage:
    python3 clone_node_modules.py <main-checkout> <worktree>

Both paths must live on the same APFS volume.
"""
import ctypes
import os
import sys
import time

WORKSPACE_PARENTS = ("apps", "mfes", "libs", "servers", "lambdas", "creative-renderers")

libc = ctypes.CDLL("/usr/lib/libSystem.B.dylib", use_errno=True)
libc.clonefile.argtypes = [ctypes.c_char_p, ctypes.c_char_p, ctypes.c_uint32]
libc.clonefile.restype = ctypes.c_int


def clonefile(src: str, dst: str) -> None:
    rc = libc.clonefile(src.encode(), dst.encode(), 0)
    if rc != 0:
        errno = ctypes.get_errno()
        raise OSError(errno, os.strerror(errno), src, None, dst)


def iter_workspace_node_modules(main_checkout: str):
    for parent in WORKSPACE_PARENTS:
        parent_path = os.path.join(main_checkout, parent)
        if not os.path.isdir(parent_path):
            continue
        for child in os.listdir(parent_path):
            src = os.path.join(parent_path, child, "node_modules")
            if os.path.isdir(src):
                yield parent, child, src


def main(main_checkout: str, worktree: str) -> None:
    src_root = os.path.join(main_checkout, "node_modules")
    dst_root = os.path.join(worktree, "node_modules")

    if not os.path.isdir(src_root):
        sys.exit(f"source checkout has no node_modules: {src_root}")
    if os.path.exists(dst_root):
        sys.exit(f"worktree already has node_modules: {dst_root}")

    t0 = time.time()
    clonefile(src_root, dst_root)
    t_root = time.time() - t0

    t0 = time.time()
    count = 0
    for parent, child, src in iter_workspace_node_modules(main_checkout):
        dst_parent = os.path.join(worktree, parent, child)
        os.makedirs(dst_parent, exist_ok=True)
        clonefile(src, os.path.join(dst_parent, "node_modules"))
        count += 1
    t_nested = time.time() - t0

    print(f"root node_modules: {t_root * 1000:.0f}ms")
    print(f"nested workspaces ({count}): {t_nested * 1000:.0f}ms")
    print(f"total: {(t_root + t_nested) * 1000:.0f}ms")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(f"usage: {sys.argv[0]} <main-checkout> <worktree>")
    main(sys.argv[1], sys.argv[2])
